    private void btnEnviarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEnviarActionPerformed
        if (listaPendentes.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "A fila de pendentes está vazia!", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        btnEnviar.setEnabled(false);
        taRespostas.append("\n[Cliente] Enviando lista de " + listaPendentes.size() + " evento(s) ao setvidor...");
        
        java.util.List<Evento> eventosParaEnviar = new java.util.ArrayList<>(listaPendentes);
        
        javax.swing.SwingWorker<Resposta, Void> worker = new javax.swing.SwingWorker<>() {
            @Override
            protected Resposta doInBackground() throws Exception {
                Requisicao req = new Requisicao("REGISTRAR", "", eventosParaEnviar);
                return servicoCliente.enviar(req);
            }
            
            @Override
            protected void done() {
                try {
                    Resposta resp = get();
                    taRespostas.append(String.format("\n[%s] Status: %s", resp.getTimestamp(), resp.getStatus()));
                    for (String dado : resp.getDados()) {
                        taRespostas.append("\n" + dado);
                    }
                    
                    if ("OK".equalsIgnoreCase(resp.getStatus())) {
                        listaPendentes.clear();
                        atualizarAreaPendentes();
                    }
                } catch (Exception ex) {
                    taRespostas.append("\n[ERRO] Falha ao enviar requisição: " + ex.getMessage());
                } finally {
                    btnEnviar.setEnabled(true);
                }
            }
        };
        
        worker.execute();
    }//GEN-LAST:event_btnEnviarActionPerformed

    private void btnConsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarActionPerformed
        String filtro = (String) cbFiltro.getSelectedItem();
        btnConsultar.setEnabled(false);
        
        javax.swing.SwingWorker<Resposta, Void> worker = new javax.swing.SwingWorker<>() {
            @Override
            protected Resposta doInBackground() throws Exception {
                Requisicao req = new Requisicao("LISTAR", filtro, new java.util.ArrayList<>());
                return servicoCliente.enviar(req);
            }
            
            @Override
            protected void done() {
                try {
                    Resposta resp = get();
                    taRespostas.setText("=== CONSULTA DE LOGS (" + filtro + ") ===");
                    taRespostas.append("\nData/Hora: " + resp.getTimestamp() + " | Status: " + resp.getStatus());
                    taRespostas.append("\n----------------------------------------------------------------");
                    
                    if (resp.getDados().isEmpty()) {
                        taRespostas.append("\nNenhum log encontrado para o filtro selecionado.");
                    } else {
                        for (String linha : resp.getDados()) {
                            taRespostas.append("\n" + linha);
                        }
                    }
                } catch (Exception ex) {
                    taRespostas.append("\n[ERRO] Falha na consulta: " + ex.getMessage());
                } finally {
                    btnConsultar.setEnabled(true);
                }
            }
        };
        
        worker.execute();
    }//GEN-LAST:event_btnConsultarActionPerformed

    private void btnAdicionarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAdicionarActionPerformed
        String origem = tfOrigem.getText().trim();
        String mensagem = tfMensagem.getText().trim();
        String nivel = (String) cbNivel.getSelectedItem();
        
        if (origem.isEmpty() || mensagem.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Preencha a origem e a mensagem!", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        Evento evento = new Evento(nivel, origem, mensagem);
        listaPendentes.add(evento);
        
        atualizarAreaPendentes();
        
        tfOrigem.setText("");
        tfMensagem.setText("");
        tfOrigem.requestFocus();
    }//GEN-LAST:event_btnAdicionarActionPerformed

